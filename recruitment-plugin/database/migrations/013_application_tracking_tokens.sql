-- Run only after the Oracle owner reviews and approves the target schema.
-- Adds a unique public reference to each HRS application and links dynamic
-- form snapshots directly to that application.
DECLARE
    table_count NUMBER;
    column_count NUMBER;
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'HRS_LAMARAN';
    IF table_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20031, 'HRS_LAMARAN is missing.');
    END IF;

    SELECT COUNT(*) INTO table_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'RECRUIT_FORM_SUBMISSIONS';
    IF table_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20032, 'RECRUIT_FORM_SUBMISSIONS is missing; run migration 008 first.');
    END IF;

    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_LAMARAN'
      AND COLUMN_NAME = 'APPLICATION_TOKEN';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE HRS_LAMARAN ADD (APPLICATION_TOKEN VARCHAR2(64 CHAR))';
    END IF;

    EXECUTE IMMEDIATE
        'UPDATE HRS_LAMARAN SET APPLICATION_TOKEN = ''DAW-'' || TO_CHAR(SYSTIMESTAMP, ''YYYY'') || ''-'' || RAWTOHEX(SYS_GUID()) WHERE APPLICATION_TOKEN IS NULL';

    SELECT COUNT(*) INTO object_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'UK_HRS_LAMARAN_TOKEN';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE UNIQUE INDEX UK_HRS_LAMARAN_TOKEN ON HRS_LAMARAN (APPLICATION_TOKEN)';
    END IF;

    EXECUTE IMMEDIATE
        'ALTER TABLE HRS_LAMARAN MODIFY (APPLICATION_TOKEN NOT NULL)';

    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'RECRUIT_FORM_SUBMISSIONS'
      AND COLUMN_NAME = 'LAMARAN_ID';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE RECRUIT_FORM_SUBMISSIONS ADD (LAMARAN_ID NUMBER(19,0))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_RECRUIT_SUBM_LAMARAN';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE RECRUIT_FORM_SUBMISSIONS ADD CONSTRAINT FK_RECRUIT_SUBM_LAMARAN FOREIGN KEY (LAMARAN_ID) REFERENCES HRS_LAMARAN (LAMARAN_ID)';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'UK_RECRUIT_SUBM_LAMARAN';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE UNIQUE INDEX UK_RECRUIT_SUBM_LAMARAN ON RECRUIT_FORM_SUBMISSIONS (LAMARAN_ID)';
    END IF;
END;
/
