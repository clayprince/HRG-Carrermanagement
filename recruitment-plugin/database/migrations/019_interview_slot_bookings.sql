-- Run only after the Oracle owner verifies migrations 018 and the target schema.
-- Reservations are bound to an application and one HR/User schedule slot.
    DECLARE
        object_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO object_count
        FROM USER_TABLES
        WHERE TABLE_NAME = 'HRS_INTERVIEW_SCHEDULE';
        IF object_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20082, 'Apply migration 018 before creating interview bookings.');
        END IF;

        SELECT COUNT(*) INTO object_count
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'HRS_INTERVIEW_SCHEDULE'
        AND COLUMN_NAME IN ('SCHEDULE_ID', 'INTERVIEW_TYPE', 'SCHEDULE_DATE', 'CAPACITY');
        IF object_count <> 4 THEN
            RAISE_APPLICATION_ERROR(-20085, 'HRS_INTERVIEW_SCHEDULE is missing columns required for bookings.');
        END IF;

        SELECT COUNT(*) INTO object_count
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'HRS_LAMARAN'
        AND COLUMN_NAME IN ('LAMARAN_ID', 'PROFILE_KANDIDAT_ID', 'STATUS_TERKINI', 'STATUS_AKHIR');
        IF object_count <> 4 THEN
            RAISE_APPLICATION_ERROR(-20083, 'HRS_LAMARAN is missing columns required for applicant interview bookings.');
        END IF;

        SELECT COUNT(*) INTO object_count
        FROM USER_TABLES
        WHERE TABLE_NAME = 'HRS_INTERVIEW_BOOKING';

        IF object_count = 0 THEN
            EXECUTE IMMEDIATE '
                CREATE TABLE HRS_INTERVIEW_BOOKING (
                    BOOKING_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                    LAMARAN_ID NUMBER(19,0) NOT NULL,
                    SCHEDULE_ID NUMBER(19,0) NOT NULL,
                    INTERVIEW_TYPE VARCHAR2(10 CHAR) NOT NULL,
                    BOOKING_STATUS VARCHAR2(10 CHAR) DEFAULT ''BOOKED'' NOT NULL,
                    BOOKED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    CONSTRAINT PK_HRS_INTERVIEW_BOOKING PRIMARY KEY (BOOKING_ID),
                    CONSTRAINT FK_HRIB_APPLICATION FOREIGN KEY (LAMARAN_ID) REFERENCES HRS_LAMARAN (LAMARAN_ID),
                    CONSTRAINT FK_HRIB_SCHEDULE FOREIGN KEY (SCHEDULE_ID) REFERENCES HRS_INTERVIEW_SCHEDULE (SCHEDULE_ID),
                    CONSTRAINT CK_HRIB_TYPE CHECK (INTERVIEW_TYPE IN (''HR'', ''USER'')),
                    CONSTRAINT CK_HRIB_STATUS CHECK (BOOKING_STATUS IN (''BOOKED'')),
                    CONSTRAINT UK_HRIB_APPLICATION_TYPE UNIQUE (LAMARAN_ID, INTERVIEW_TYPE)
                )';
        ELSE
            SELECT COUNT(*) INTO object_count
            FROM USER_TAB_COLUMNS
            WHERE TABLE_NAME = 'HRS_INTERVIEW_BOOKING'
            AND COLUMN_NAME IN (
                'BOOKING_ID', 'LAMARAN_ID', 'SCHEDULE_ID', 'INTERVIEW_TYPE',
                'BOOKING_STATUS', 'BOOKED_AT'
            );
            IF object_count <> 6 THEN
                RAISE_APPLICATION_ERROR(-20084, 'HRS_INTERVIEW_BOOKING exists with an incompatible column definition.');
            END IF;
        END IF;
    END;
    /
