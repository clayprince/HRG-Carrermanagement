-- Run only after the Oracle owner reviews and approves the target schema.
-- Stores HR interview results per application and grants access to one
-- explicitly selected active User Department account.
DECLARE
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count
    FROM USER_TABLES
    WHERE TABLE_NAME IN ('HRS_LAMARAN', 'HRS_ROLE_AKSES', 'HRS_HASIL_WAWANCARA_USER');
    IF object_count <> 3 THEN
        RAISE_APPLICATION_ERROR(-20061, 'Required application, account, or department interview table is missing.');
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'HRS_HASIL_WAWANCARA_HR';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE HRS_HASIL_WAWANCARA_HR (
                LAMARAN_ID NUMBER(19,0) NOT NULL,
                STATUS_HASIL VARCHAR2(20 CHAR) NOT NULL,
                REKOMENDASI VARCHAR2(40 CHAR) NOT NULL,
                CATATAN_WAWANCARA VARCHAR2(2000 CHAR),
                NAMA_PEWAWANCARA VARCHAR2(100 CHAR) NOT NULL,
                ROLE_AKSES_ID NUMBER(19,0),
                DIBUAT_PADA TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                DIPERBARUI_PADA TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_HRS_HASIL_WAWANCARA_HR PRIMARY KEY (LAMARAN_ID),
                CONSTRAINT FK_HRS_HASIL_HR_LAMARAN FOREIGN KEY (LAMARAN_ID)
                    REFERENCES HRS_LAMARAN (LAMARAN_ID),
                CONSTRAINT FK_HRS_HASIL_HR_AKSES FOREIGN KEY (ROLE_AKSES_ID)
                    REFERENCES HRS_ROLE_AKSES (ROLE_AKSES_ID),
                CONSTRAINT CK_HRS_HASIL_HR_STATUS CHECK (STATUS_HASIL IN (''LOLOS'', ''TIDAK_LOLOS'')),
                CONSTRAINT CK_HRS_HASIL_HR_TUJUAN CHECK (
                    (STATUS_HASIL = ''LOLOS'' AND ROLE_AKSES_ID IS NOT NULL)
                    OR (STATUS_HASIL = ''TIDAK_LOLOS'' AND ROLE_AKSES_ID IS NULL)
                )
            )';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_HASIL_WAWANCARA_HR'
      AND COLUMN_NAME = 'CATATAN_WAWANCARA';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_HASIL_WAWANCARA_HR ADD (CATATAN_WAWANCARA VARCHAR2(2000 CHAR))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_HASIL_WAWANCARA_USER'
      AND COLUMN_NAME = 'LAMARAN_ID';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_HASIL_WAWANCARA_USER ADD (LAMARAN_ID NUMBER(19,0))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_HRS_HASIL_USER_LAMARAN';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE HRS_HASIL_WAWANCARA_USER
            ADD CONSTRAINT FK_HRS_HASIL_USER_LAMARAN FOREIGN KEY (LAMARAN_ID)
                REFERENCES HRS_LAMARAN (LAMARAN_ID)';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'UK_HRS_HASIL_USER_LAMARAN';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE UNIQUE INDEX UK_HRS_HASIL_USER_LAMARAN
            ON HRS_HASIL_WAWANCARA_USER (LAMARAN_ID)';
    END IF;
END;
/
