-- Run only after the Oracle owner reviews and approves the target schema.
-- Stores independently configured HR and User interview slots.
DECLARE
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'HRS_INTERVIEW_SCHEDULE';

    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE HRS_INTERVIEW_SCHEDULE (
                SCHEDULE_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                INTERVIEW_TYPE VARCHAR2(10 CHAR) NOT NULL,
                SCHEDULE_DATE DATE NOT NULL,
                START_TIME VARCHAR2(5 CHAR) NOT NULL,
                END_TIME VARCHAR2(5 CHAR) NOT NULL,
                METHOD VARCHAR2(10 CHAR) NOT NULL,
                PLATFORM VARCHAR2(100 CHAR),
                MEETING_LINK VARCHAR2(500 CHAR),
                LOCATION VARCHAR2(255 CHAR),
                CAPACITY NUMBER(3,0) DEFAULT 1 NOT NULL,
                CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_HRS_INTERVIEW_SCHEDULE PRIMARY KEY (SCHEDULE_ID),
                CONSTRAINT CK_HRIS_TYPE CHECK (INTERVIEW_TYPE IN (''HR'', ''USER'')),
                CONSTRAINT CK_HRIS_METHOD CHECK (METHOD IN (''ONLINE'', ''OFFLINE'')),
                CONSTRAINT CK_HRIS_TIME CHECK (START_TIME < END_TIME),
                CONSTRAINT CK_HRIS_CAPACITY CHECK (CAPACITY BETWEEN 1 AND 100),
                CONSTRAINT UK_HRIS_TYPE_DATE_START UNIQUE (INTERVIEW_TYPE, SCHEDULE_DATE, START_TIME)
            )';
    ELSE
        SELECT COUNT(*) INTO object_count
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'HRS_INTERVIEW_SCHEDULE'
          AND COLUMN_NAME IN (
              'SCHEDULE_ID', 'INTERVIEW_TYPE', 'SCHEDULE_DATE', 'START_TIME',
              'END_TIME', 'METHOD', 'PLATFORM', 'MEETING_LINK', 'LOCATION',
              'CAPACITY', 'CREATED_AT'
          );
        IF object_count <> 11 THEN
            RAISE_APPLICATION_ERROR(-20081, 'HRS_INTERVIEW_SCHEDULE exists with an incompatible column definition.');
        END IF;
    END IF;
END;
/
