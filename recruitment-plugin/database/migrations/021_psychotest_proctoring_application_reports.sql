-- Run only after the Oracle owner reviews and approves the target schema.
-- Existing proctoring sessions cannot be mapped back to an application from
-- their HMAC session IDs, so APPLICATION_ID intentionally remains NULL for
-- historical rows.
DECLARE
    column_count NUMBER;
    constraint_count NUMBER;
    index_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_PSY_PROCTOR_SESSIONS'
      AND COLUMN_NAME = 'APPLICATION_ID';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_PSY_PROCTOR_SESSIONS ADD (APPLICATION_ID NUMBER(19,0))';
    END IF;

    SELECT COUNT(*) INTO constraint_count
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'HRS_PSY_PROCTOR_SESSIONS'
      AND CONSTRAINT_NAME = 'FK_HPSPS_APPLICATION';
    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE HRS_PSY_PROCTOR_SESSIONS ADD CONSTRAINT FK_HPSPS_APPLICATION
             FOREIGN KEY (APPLICATION_ID) REFERENCES HRS_LAMARAN (LAMARAN_ID)';
    END IF;

    SELECT COUNT(*) INTO index_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_HPSPS_APPLICATION';
    IF index_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE INDEX IX_HPSPS_APPLICATION
             ON HRS_PSY_PROCTOR_SESSIONS (APPLICATION_ID, RETENTION_UNTIL)';
    END IF;

    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_PSY_PROCTOR_EVENTS'
      AND COLUMN_NAME = 'ASSESSMENT_STAGE';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE HRS_PSY_PROCTOR_EVENTS ADD (ASSESSMENT_STAGE VARCHAR2(16 CHAR))';
    END IF;

    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_PSY_PROCTOR_EVENTS'
      AND COLUMN_NAME = 'EVENT_TOKEN';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE HRS_PSY_PROCTOR_EVENTS ADD (EVENT_TOKEN VARCHAR2(64 CHAR))';
    END IF;

    SELECT COUNT(*) INTO index_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'UX_HPSPE_EVENT_TOKEN';
    IF index_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE UNIQUE INDEX UX_HPSPE_EVENT_TOKEN
             ON HRS_PSY_PROCTOR_EVENTS (EVENT_TOKEN)';
    END IF;
END;
