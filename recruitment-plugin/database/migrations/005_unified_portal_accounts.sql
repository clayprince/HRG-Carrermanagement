-- Run only after review and approval by the Oracle owner.
-- Unifies Admin HR and department accounts in HRS_ROLE_AKSES.
ALTER TABLE HRS_ROLE_AKSES MODIFY (
    EMAIL VARCHAR2(254 CHAR),
    KATA_SANDI VARCHAR2(255 CHAR)
);

DECLARE
    column_count NUMBER;
    constraint_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_ROLE_AKSES'
      AND COLUMN_NAME = 'PERAN';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_ROLE_AKSES ADD (PERAN VARCHAR2(30 CHAR))';
    END IF;

    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_ROLE_AKSES'
      AND COLUMN_NAME = 'STATUS_AKUN';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_ROLE_AKSES ADD (STATUS_AKUN VARCHAR2(8 CHAR) DEFAULT ''ACTIVE'' NOT NULL)';
    END IF;

    SELECT COUNT(*) INTO constraint_count
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'HRS_ROLE_AKSES'
      AND CONSTRAINT_NAME = 'HRS_ROLE_AKSES_PERAN_CK';

    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_ROLE_AKSES ADD CONSTRAINT HRS_ROLE_AKSES_PERAN_CK CHECK (PERAN IN (''ADMIN_HR'', ''KEPALA_DEPARTEMEN''))';
    END IF;

    SELECT COUNT(*) INTO constraint_count
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'HRS_ROLE_AKSES'
      AND CONSTRAINT_NAME = 'HRS_ROLE_AKSES_STATUS_CK';

    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_ROLE_AKSES ADD CONSTRAINT HRS_ROLE_AKSES_STATUS_CK CHECK (STATUS_AKUN IN (''ACTIVE'', ''INACTIVE''))';
    END IF;
END;
/

UPDATE HRS_ROLE_AKSES
SET PERAN = CASE
    WHEN DEPARTEMEN_ID IS NULL THEN 'ADMIN_HR'
    ELSE 'KEPALA_DEPARTEMEN'
END
WHERE PERAN IS NULL;

COMMIT;
