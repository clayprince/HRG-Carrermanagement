-- Run only after review and approval by the Oracle owner.
-- Existing portal accounts default to ACTIVE to preserve current access.
DECLARE
    column_count NUMBER;
    constraint_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HR_USER'
      AND COLUMN_NAME = 'STATUS_AKUN';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HR_USER ADD (STATUS_AKUN VARCHAR2(8 CHAR) DEFAULT ''ACTIVE'' NOT NULL)';
    END IF;

    SELECT COUNT(*) INTO constraint_count
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'HR_USER'
      AND CONSTRAINT_NAME = 'HR_USER_STATUS_AKUN_CK';

    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HR_USER ADD CONSTRAINT HR_USER_STATUS_AKUN_CK CHECK (STATUS_AKUN IN (''ACTIVE'', ''INACTIVE''))';
    END IF;

    SELECT COUNT(*) INTO column_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'USERS_AD'
      AND COLUMN_NAME = 'STATUS_AKUN';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE USERS_AD ADD (STATUS_AKUN VARCHAR2(8 CHAR) DEFAULT ''ACTIVE'' NOT NULL)';
    END IF;

    SELECT COUNT(*) INTO constraint_count
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'USERS_AD'
      AND CONSTRAINT_NAME = 'USERS_AD_STATUS_AKUN_CK';

    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE USERS_AD ADD CONSTRAINT USERS_AD_STATUS_AKUN_CK CHECK (STATUS_AKUN IN (''ACTIVE'', ''INACTIVE''))';
    END IF;
END;
/
