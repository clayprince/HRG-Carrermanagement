-- Run only after the Oracle owner reviews and approves the target schema.
-- Evidence files stay in the private WordPress storage directory; Oracle
-- stores consent, event, and retention metadata only.
DECLARE
    table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'HRS_PSY_PROCTOR_SESSIONS';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE HRS_PSY_PROCTOR_SESSIONS (
                SESSION_ID VARCHAR2(64 CHAR) NOT NULL,
                KANDIDAT_ID NUMBER(19,0) NOT NULL,
                CONSENT_VERSION VARCHAR2(20 CHAR) NOT NULL,
                CONSENT_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                IDENTITY_STATUS VARCHAR2(24 CHAR) DEFAULT ''PENDING'' NOT NULL,
                CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                COMPLETED_AT TIMESTAMP(6),
                RETENTION_UNTIL TIMESTAMP(6) NOT NULL,
                UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_HRS_PSY_PROCTOR_SESS PRIMARY KEY (SESSION_ID),
                CONSTRAINT FK_HRS_PSY_PROCTOR_CAND FOREIGN KEY (KANDIDAT_ID)
                    REFERENCES HRS_PROFIL_KANDIDAT (KANDIDAT_ID)
            )';
    END IF;

    SELECT COUNT(*) INTO table_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'HRS_PSY_PROCTOR_EVENTS';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE HRS_PSY_PROCTOR_EVENTS (
                EVENT_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                SESSION_ID VARCHAR2(64 CHAR) NOT NULL,
                EVENT_TYPE VARCHAR2(32 CHAR) NOT NULL,
                FILE_KEY VARCHAR2(64 CHAR),
                EVENT_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
                ACTOR_USER_ID NUMBER(19,0),
                TARGET_EVENT_ID NUMBER(19,0),
                CONSTRAINT PK_HRS_PSY_PROCTOR_EVENT PRIMARY KEY (EVENT_ID),
                CONSTRAINT FK_HRS_PSY_PROCTOR_SESSION FOREIGN KEY (SESSION_ID)
                    REFERENCES HRS_PSY_PROCTOR_SESSIONS (SESSION_ID)
            )';
    END IF;

    SELECT COUNT(*) INTO table_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_HRS_PSY_PROCTOR_CAND';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE INDEX IX_HRS_PSY_PROCTOR_CAND ON HRS_PSY_PROCTOR_SESSIONS (KANDIDAT_ID, RETENTION_UNTIL)';
    END IF;

    SELECT COUNT(*) INTO table_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_HRS_PSY_PROCTOR_EVENT';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE
            'CREATE INDEX IX_HRS_PSY_PROCTOR_EVENT ON HRS_PSY_PROCTOR_EVENTS (SESSION_ID, EVENT_AT)';
    END IF;
END;
/
