-- Run only after the Oracle owner reviews and approves the target schema.
DECLARE
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_SLOT_WAWANCARA'
      AND COLUMN_NAME = 'JENIS_WAWANCARA';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_SLOT_WAWANCARA ADD (JENIS_WAWANCARA VARCHAR2(24 CHAR))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_SLOT_WAWANCARA'
      AND COLUMN_NAME = 'DEPARTEMEN_ID';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_SLOT_WAWANCARA ADD (DEPARTEMEN_ID NUMBER(19,0))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_BOOKING_INTERVIEW'
      AND COLUMN_NAME = 'LAMARAN_ID';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_BOOKING_INTERVIEW ADD (LAMARAN_ID NUMBER(19,0))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HRS_BOOKING_INTERVIEW'
      AND COLUMN_NAME = 'JENIS_WAWANCARA';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HRS_BOOKING_INTERVIEW ADD (JENIS_WAWANCARA VARCHAR2(24 CHAR))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'CK_HRS_SLOT_WAWANCARA_TYPE';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE HRS_SLOT_WAWANCARA ADD CONSTRAINT CK_HRS_SLOT_WAWANCARA_TYPE
            CHECK (
                JENIS_WAWANCARA IS NULL
                OR (JENIS_WAWANCARA = ''INTERVIEW_HR'' AND DEPARTEMEN_ID IS NULL)
                OR (JENIS_WAWANCARA = ''INTERVIEW_USER'' AND DEPARTEMEN_ID IS NOT NULL)
            )';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'CK_HRS_BOOKING_INTERVIEW_TYPE';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE HRS_BOOKING_INTERVIEW ADD CONSTRAINT CK_HRS_BOOKING_INTERVIEW_TYPE
            CHECK (JENIS_WAWANCARA IS NULL OR JENIS_WAWANCARA IN (''INTERVIEW_HR'', ''INTERVIEW_USER''))';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_HRS_SLOT_WAWANCARA_DEPT';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE HRS_SLOT_WAWANCARA ADD CONSTRAINT FK_HRS_SLOT_WAWANCARA_DEPT
            FOREIGN KEY (DEPARTEMEN_ID) REFERENCES HRS_DEPARTEMEN (DEPARTEMEN_ID)';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_HRS_BOOKING_INTERVIEW_APP';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE HRS_BOOKING_INTERVIEW ADD CONSTRAINT FK_HRS_BOOKING_INTERVIEW_APP
            FOREIGN KEY (LAMARAN_ID) REFERENCES HRS_LAMARAN (LAMARAN_ID)';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'UX_HRS_BOOKING_INTERVIEW_APP';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE UNIQUE INDEX UX_HRS_BOOKING_INTERVIEW_APP
            ON HRS_BOOKING_INTERVIEW (LAMARAN_ID, JENIS_WAWANCARA)';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_HRS_SLOT_WAWANCARA_TYPE';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE INDEX IX_HRS_SLOT_WAWANCARA_TYPE
            ON HRS_SLOT_WAWANCARA (JENIS_WAWANCARA, DEPARTEMEN_ID, START_AT)';
    END IF;

    SELECT COUNT(*) INTO object_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_HRS_BOOKING_INTERVIEW_SLOT';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE INDEX IX_HRS_BOOKING_INTERVIEW_SLOT
            ON HRS_BOOKING_INTERVIEW (SLOT_WAWANCARA_ID, STATUS_PEMESANAN)';
    END IF;
END;
